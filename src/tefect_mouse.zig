const std = @import("std");
const Console = @import("tefect_console.zig");
const TefectError = @import("tefect_buffer.zig").TefectError;
const EnableMouseInput = Console.EnableMouseInput;
const DisbleMouseInput = Console.DisbleMouseInput;

const Windows = @import("builtin").os.tag == .windows;

pub const MouseTrackingProtocols = enum(u2) {

    /// `X10 Tracking`
    ///
    /// The original and simplest mouse tracking protocol.
    /// It only reports **button press** events.
    /// Button releases, mouse movement, dragging, and modifier-only changes are not reported.
    X10,

    /// `Normal Tracking`
    ///
    /// The standard mouse tracking protocol used by most terminal applications.
    /// Reports **button presses** and **button releases**.
    /// Mouse movement is ignored unless another tracking mode is enabled.
    X11,

    /// `Button Event Tracking`
    ///
    /// Extends the normal tracking protocol by also reporting mouse movement
    /// while **at least one mouse button is held down** (dragging).
    ///
    /// Reports:
    /// - Button press
    /// - Button release
    /// - Drag (mouse movement with a pressed button)
    ///
    /// Does **not** report normal mouse movement when no buttons are pressed.
    ButtonEventTracking,

    /// `Any Motion Tracking`
    ///
    /// Reports every mouse event generated by the terminal.
    ///
    /// Reports:
    /// - Button press
    /// - Button release
    /// - Drag
    /// - Mouse movement even when no buttons are pressed (hover)
    ///
    /// This protocol generates the largest number of events and is useful
    /// for applications requiring continuous mouse tracking.
    AnyMotionTracking,

    pub fn toAnsi(Protocol: MouseTrackingProtocols, flag: enum {Enable, Disble}) []const u8 {
        return switch (Protocol) {
            .X10 => "\x1b[?9",
            .X11 => "\x1b[?1000",
            .ButtonEventTracking => "\x1b[?1002",
            .AnyMotionTracking => "\x1b[?1003"
        } ++ if (flag == .Enable) "h" else "l";
    }
};


pub const ScrollWheelDirections = enum(u2) {
    Up,
    Down,
    Left,
    Right
};

pub const Buttons = enum(u2) {
    Left,
    Middle,
    Right,
    Release
};


pub const CbByteLayout = packed struct(u8) {

    ButtonBits: packed union {
        ScrollWheelDirection: ScrollWheelDirections,
        Button: Buttons
    },

    Shift: bool,
    Alt: bool,
    Ctrl: bool,
    Motion: bool,
    Wheel: bool,
    Unused: bool
};


pub const MouseEventType = enum(u3) {
    Press,
    Release,
    Drag,
    Scroll,
    Hover
}; 


pub const MouseEvent = packed struct(u40) {

    Type: MouseEventType,

    Location: packed struct(u32) {
        x: u16,
        y: u16
    },

    Action: packed union {
        ScrollWheelDirection: ScrollWheelDirections,
        Button: Buttons,
    },

    Shift: bool,
    Alt: bool,
    Ctrl: bool
};


fn SpecifyType(cb: CbByteLayout) MouseEventType {
    if (cb.Wheel) return .Scroll;
    if (cb.Motion) {
        return if (cb.ButtonBits.Button == .Release) .Hover else .Drag;
    }
    else {
        return if (cb.ButtonBits.Button != .Release) .Press else .Release; 
    }
}

pub fn FullMouseEventParser(buffer: [6]u8) TefectError!MouseEvent {
    if (
        buffer[0] == 27
        and buffer[1] == 91
        and buffer[2] == 'M'
    ) {
    
        const ParsedCbByte: CbByteLayout = @bitCast(buffer[3] - 32);
        var mouseEvent: MouseEvent = undefined;

        mouseEvent.Type = SpecifyType(ParsedCbByte);

        mouseEvent.Location = .{
            .x = buffer[4] -| 32,
            .y = buffer[5] -| 32
        };

        mouseEvent.Action = @bitCast(ParsedCbByte.ButtonBits);

        mouseEvent.Shift = ParsedCbByte.Shift;
        mouseEvent.Alt = ParsedCbByte.Alt;
        mouseEvent.Ctrl = ParsedCbByte.Ctrl;        

        return mouseEvent;
    }
    else return TefectError.NotAMouseEvent;
}

pub fn WindowsNoCheck3ByteMouseEventParser(buffer: [3]u8) MouseEvent {

    const ParsedCbByte: CbByteLayout = @bitCast(buffer[0] - 32); 
    var mouseEvent: MouseEvent = undefined;

    mouseEvent.Type = SpecifyType(ParsedCbByte);

    mouseEvent.Location = .{
            .x = buffer[1] -| 32,
            .y = buffer[2] -| 32
    };

    mouseEvent.Action = @bitCast(ParsedCbByte.ButtonBits);

    mouseEvent.Shift = ParsedCbByte.Shift;
    mouseEvent.Alt = ParsedCbByte.Alt;
    mouseEvent.Ctrl = ParsedCbByte.Ctrl;        

    return mouseEvent;
}